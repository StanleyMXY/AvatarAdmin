/**
 * What is wrong with `value` for the key of `spec`, as a reason code (`reason.<code>`), or null.
 * The server decides in the end; this only stops what is plainly wrong before a request is made.
 * Relations between two keys (for example a minimum below a maximum) are left to the server.
 */
export function validateValue(spec: ConfigKeySpec, value: unknown): string | null {
  switch (spec.kind) {
    case 'int': {
      if (typeof value !== 'number' || !Number.isInteger(value)) return 'NOT_AN_INTEGER';
      if (spec.min !== undefined && value < spec.min) return 'OUT_OF_RANGE';
      if (spec.max !== undefined && value > spec.max) return 'OUT_OF_RANGE';
      return null;
    }
    case 'number': {
      return typeof value === 'number' && Number.isFinite(value) ? null : 'NOT_AN_INTEGER';
    }
    case 'bool':
      return typeof value === 'boolean' ? null : 'NOT_BOOLEAN';
    case 'url': {
      if (typeof value !== 'string') return 'NOT_HTTPS';
      const check = validateServerLink(value);
      return check.ok ? null : check.reasonKey;
    }
    case 'string':
      return typeof value === 'string' ? null : 'EMPTY_NOT_ALLOWED';
    case 'json':
      return spec.validate ? spec.validate(value) : null;
  }
}
