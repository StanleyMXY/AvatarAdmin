// One entry per operating parameter of contract 17.5 (`AppConfig`). The schema holds no default
// value: the default of a key is whatever `GET /config` reports as `defaultValue`. Labels and
// descriptions are in the language files as `config.<key>.label` and `config.<key>.desc`.

export type ConfigKind = 'int' | 'number' | 'string' | 'bool' | 'json' | 'url';

export type ConfigKeySpec = {
  key: string;
  kind: ConfigKind;
  /** The permission that may edit it (`CONFIG:MANAGE` for system keys). */
  editPermission: PermissionCode;
  /** The part of the key before the first dot: how the system page groups it. */
  group: string;
  min?: number;
  max?: number;
  /** A risk the row must spell out (`config.<key>.risk`). */
  risk?: boolean;
  /** The page that has the dedicated editor of this key; the row is read-only with a link there. */
  editedElsewhere?: string;
  /** A rule for the value, returning a reason code (`reason.<code>`) or null. */
  validate?: (value: unknown) => string | null;
};

const isPositiveInt = (v: unknown): v is number =>
  typeof v === 'number' && Number.isInteger(v) && v >= 1;

const LANGUAGE_TAG = /^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})*$/;

const VALIDATORS: Record<string, (value: unknown) => string | null> = {
  // The thresholds are positive and rise with the stage.
  'companionship.stage_thresholds': (v) => {
    const o = v as { BONDING?: unknown; CLOSE?: unknown } | null;
    if (typeof o !== 'object' || o === null || Array.isArray(o)) return 'OUT_OF_RANGE';
    if (!Number.isInteger(o.BONDING) || !Number.isInteger(o.CLOSE)) return 'NOT_AN_INTEGER';
    if (!isPositiveInt(o.BONDING) || !isPositiveInt(o.CLOSE)) return 'OUT_OF_RANGE';
    return o.BONDING < o.CLOSE ? null : 'OUT_OF_RANGE';
  },
  // 1 to 20 different positive whole numbers of days.
  'milestone.days': (v) => {
    if (!Array.isArray(v) || v.length < 1 || v.length > 20) return 'OUT_OF_RANGE';
    if (!v.every((x) => typeof x === 'number' && Number.isInteger(x))) return 'NOT_AN_INTEGER';
    if (!v.every(isPositiveInt)) return 'OUT_OF_RANGE';
    return new Set(v).size === v.length ? null : 'OUT_OF_RANGE';
  },
  // Language tags, at most 35 characters each, all different, and `en` among them.
  'app.supported_locales': (v) => {
    if (!Array.isArray(v) || !v.every((x) => typeof x === 'string')) return 'INVALID_LANGUAGE_TAG';
    const list = v as string[];
    if (!list.every((x) => LANGUAGE_TAG.test(x) && x.length <= 35)) return 'INVALID_LANGUAGE_TAG';
    if (new Set(list).size !== list.length) return 'OUT_OF_RANGE';
    return list.includes('en') ? null : 'OUT_OF_RANGE';
  },
  // ISO 3166-1 alpha-2 codes, two capital letters.
  'sms.allowed_country_codes': (v) =>
    Array.isArray(v) && v.every((x) => typeof x === 'string' && /^[A-Z]{2}$/.test(x))
      ? null
      : 'OUT_OF_RANGE',
  // ISO 639-1 codes, two lower-case letters.
  'chat.conversation_languages': (v) =>
    Array.isArray(v) && v.every((x) => typeof x === 'string' && /^[a-z]{2}$/.test(x))
      ? null
      : 'INVALID_LANGUAGE_TAG',
};

